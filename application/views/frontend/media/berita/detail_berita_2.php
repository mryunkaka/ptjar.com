            <h2 class="title">Peduli Kelangkaan Minyak Goreng, Jhonlin Bangun Pabrik Berkapasitas 160 Ton Per Hari</h2>

            <div class="meta-top">
              <ul>
                <li class="d-flex align-items-center"><i class="bi bi-person"></i> <a href="blog-details.html">jhonlinmagz</li>
                <li class="d-flex align-items-center"><i class="bi bi-clock"></i> <a href="blog-details.html"><time datetime="2020-03-01">Mar 6, 2022</time></a></li>

              </ul>
