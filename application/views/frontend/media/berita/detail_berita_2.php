            <div class="content">
              <p></p>
              TANAH BUMBU – Kelangkaan minyak goreng yang terus berulang di masyarakat menjadi kepedulian PT Jhonlin Group melalui unit usaha PT. Jhonlin Agro Raya (JAR) dengan membangun pabrik minyak goreng berkapasitas 160 TPD yang bakal memproduksi minyak goreng premium kemasan 1 liter dan 2 liter dengan harga terjangkau masyarakat luas.
              </p>
              <p>
                Pembangunan pabrik milik PT Jhonlin Agro Raya (JAR), anak perusahaan Jhonlin Group, di Sungai Dua, Batulicin, Kabupaten Tanah Bumbu, Provinsi Kalsel itu dikerjakan PT Wijaya Karya Rekayasa Konstruksi dimulai 29 Juli 2021 dan ditargetkan rampung 29 Juli 2022.
              </p>
              <p>


                “Pabrik minyak goreng milik Jhonlin ini merupakan fraksinasi dari pabrik refinery yang nantinya bakal mengolah 250 ton bahan baku per hari dan mampu menghasilkan 160 ton minyak goreng per hari,” kata Direktur PT JAR Zafrinal, di Batulicin Tanah Bumbu, Kalsel, Jumat (4/3/2022).
              </p>
              <p>
                Menurut Zafrinal, saat ini proyek pembangunan menyedot tenaga kerja 250 orang warga sekitar, serta nantinya saat beroperasi pabrik yang bersistem operasi digital itu bakal menyerap 60 tenaga operasional.
              </p>
              <p>
                “Jika pabrik beroperasi tentu akan menciptakan lapangan kerja baru dan rencananya akan menyerap 80% tenaga kerja lokal,” tambahnya.
              </p>

              <p>Jhonlin berharap keberadaan pabrik minyak goreng di Kalsel bakal membantu meningkatkan perekonomian dari hulu sampai hilir dalam agro industri sawit, mengingat pasar minyak goreng sangat potensial di mana kebutuhan setiap tahun terus meningkat dan masyarakat memerlukan minyak goreng bermutu dengan harga kompetitif.
                “Target jangka panjang JAR adalah pemenuhan kapasitas dan expansi kapasitas produksi, serta hilirisasi produk CPO dengan produk berkualitas. Harapannya bisa menghasilkan produk minyak goreng berkualitas yang terjangkau masyarakat,” tegas Zafrinal.
              </p>
              <p>
                Sementara menurut GM PT JAR Mathirlan Romadhoni, target produksi pabrik baru bakal bertahap mulai 50 ton per hari hingga nantinya mencapai kapasitas maksimum 160 ton per hari.
              </p>
              <p>
                “Kemasan yang diproduksi adalah kemasan 0,5 liter, 1 liter dan 2 liter agar memenuhi daya beli masyarakat, mengingat pasar 0,5 liter, 1 liter dan 2 liter cukup besar,” kata Mathirlan.
              </p>
              <p>
                Menurutnya, area pemasaran pada tahap awal memang diprioritaskan untuk kebutuhan masyarakat Kalsel, meski tidak menutup kemungkinan bakal berkembang ke provinsi-provinsi lain di Pulau Kalimantan.
              </p>
              <p>
                “Kelebihan minyak goreng JAR adalah diproses dari lahan sawit kebun sendiri dan kualitasnya premium sehingga harganya bakal kompetitif dan terjangkau,” pungkasnya.(***)
              </p>

