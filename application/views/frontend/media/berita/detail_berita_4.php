            <div class="content">
              <p></p>
              Shipment perdana FAME PT Jhonlin Agro Raya Biodiesel telah dilaksanakan, Sabtu 11 September 2021 di Desa Sungai Dua, Kabupaten Tanah Bumbu. Kegiatan dihadiri langsung Owner Jhonlin Group beserta Jajaran Direksi unit usaha Jhonlin Group dan EAS Group.
              </p>
              <p>
                CEO EAS Group, Bambang Aria Wisena dalam sambutannya menyampaikan, “Produksi FAME PT. JAR Biodiesel tahun 2021 ini sekitar 50.000 KL yang didapatkan dari kuota tambahan thn 2021.
              </p>
              <p>
                “Pengapalan perdana di bulan September 2021, kita mengirim 5000 KL ke Pertamina Wayame. Selanjutnya, total yang akan dikirim dari September hingga Desember 2021 sekitar 50.000 KL.”

              </p>
              <p>
                “Tahun 2022 kita akan berupaya untuk mendapatkan kuota 30.000 KL perbulan, artinya mobilitas kita yang tadinya 2 kali bisa menjadi 6 kali shipment perbulan. Kita harus benar-benar proper melakukan proses produksi mengingat tantangan di tahun mendatang semakin besar. Semoga ke depan kita semakin baik. Ini adalah awal kerja kita, diharapkan semuanya dapat bekerja dengan amanah sesuai dengan prosedur, tetap kompak dan komitmen.” Tutup Bambang Aria Wisena.
              </p>


