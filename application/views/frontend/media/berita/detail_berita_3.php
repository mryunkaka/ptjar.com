            <div class="content">
              <p></p>
              Langkah awal PT. Jhonlin Agro Raya Biodiesel menjadi produsen FAME berkualitas tinggi telah terwujud. Sabtu, 11 September 2021 PT. Jhonlin Agro Raya (JAR) Biodiesel melakukan shipment perdana FAME 5000 KL di Pabrik Biodiesel PT. JAR.
              </p>
              <p>
                Syukuran pelaksanaan Shipment perdana Biodiesel PT. JAR dihadiri oleh Owner Jhonlin Group beserta jajaran Direksi unit usaha Jhonlin Group dan EAS Group. Ditandai dengan pemecahan kendi dan potong tumpeng sebagai ungkapan rasa syukur atas dilaksanakannya shipment perdana FAME PT. Jhonlin Agro Raya Biodiesel.
              </p>
              <p>
                Bambang Aria Wisena, CEO Eshan Agro Sentosa mengungkapkan “Setelah melalui proses panjang akhirnya PT. JAR melaksanakan pengapalan perdana produk FAME dengan tujuan awal ke Pertamina Wayame sebanyak 5000 kilo liter. Ini merupakan langkah besar dan berani yang dilakukan Jhonlin Group masuk ke dalam bisnis bidang usaha energi yang terbarukan,”
              </p>
              <p>
                Lanjut Bambang Aria Wisena, “Tidak hanya itu saja, kita harus berkomitmen penuh kepada negara melalui Pertamina dan Kementerian ESDM agar selalu menghasikan FAME dengan standar kualitas yang sudah ditentukan. Kami mohon doa dan support agar Pabrik Biodiesel PT. JAR dapat menjadi proyek kebanggaan Jhonlin Group serta secara umum untuk masyarakat Tanah Bumbu.”
              </p>


