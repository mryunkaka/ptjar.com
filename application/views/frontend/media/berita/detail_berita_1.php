            <h2 class="title">PT. Jhonlin Agro Raya Bangun Pabrik Kelapa Sawit Kapasitas 60 TPH Senilai 195 Miliar</h2>

            <div class="meta-top">
              <ul>
                <li class="d-flex align-items-center"><i class="bi bi-person"></i> <a href="blog-details.html">jhonlinmagz</a></li>
                <li class="d-flex align-items-center"><i class="bi bi-clock"></i> <a href="blog-details.html"><time datetime="2020-03-01">Okt 21, 2021</time></a></li>

              </ul>
            </div><!-- End meta top -->

            <div class="content">
              <p>
                Demi memenuhi kebutuhan bahan baku CPO dan mendukung program pemerintah dalam bidang industri energi terbarukan biodiesel, PT. Jhonlin Agro Raya (PT.JAR) dirikan pabrik kelapa sawit (PKS) berkapasitas 60 ton per/jam di Cantung, Kab. Kotabaru. (4/4/22)
              </p>
              <p>
                PKS Sungai Kamboyan Mill milik PT. JAR ini ditargetkan selesai dalam waktu 16 bulan kedepan dengan nilai investasi sebesar 195 Miliar. Direncanakan beroperasi bulan Juli tahun 2023.
              </p>
              <p>
                Bambang Aria Wisena, Direktur Utama PT. Eshan Agro Sentosa (PT.EAS) holding company yang membawahi PT. JAR mengatakan, PKS Sungai Kamboyan Mill ini merupakan pabrik ke-6 yang beroperasi di bawah EAS Group, sub-holding dari Jhonlin Group.
              </p>
              <p>
                “Dengan adanya pabrik ini, akan memperkuat produktifitas kita, dan sebagai konsistensi Jhonlin Group sebagai induk usaha kami, dalam industri kelapa sawit terpadu, khususnya dibidang energi terbarukan biodiesel dengan menggunakan teknologi terbaru yang ramah lingkungan” terang Bambang.
              </p>
              <p>
                Ditambahkannya, “Kami berharap, pabrik ini nantinya akan menjadi salah satu motor penggerak ekonomi di Kabupaten Kotabaru dan Kalimantan Selatan, menjadikan Kabupaten Kotabaru dan Tanah Bumbu sebagai salah satu pusat penghasil biodiesel di kawasan Indonesia bagian timur, serta mendukung program mandatory biodiesel oleh Presiden Jokowi. Dan kedepannya, semoga masyarakat di Indonesia bagian timur tidak lagi kesulitan dalam mendapatkan solar” harapnya.
              </p>
              <p>
                Untuk mencapai target produksi 360.000 Ton/tahun, di tahun 2023, PT. JAR telah mempersiapkan program kerja pabrik untuk tahun 2023.
              </p>
              <p>
                Zafrinal Direktur PT. JAR menegaskan “Untuk tahun 2023 ditargetkan utilisasi mencapai 80% dari total 60 Ton/jam dalam 4 bulan pertama di tahun 2023, oleh karena itu, kami akan membutuhkan serapan tenaga kerja lokal sebanyak 80% dari total tenag kerja” terang Zafrinal.
              </p>
              <p>
                Selain akan menyerap tenaga kerja baru, Bupati Kabupaten Kotabaru Syaid Zafar berharap, “Industri kelapa sawit di Kabupaten Kotabaru dapat meningkatkan anggaran pendapatan daerah dan memberikan kontribusi kepada petani sawit yang dapat mendistribusikan hasil sawitnya di PKS PT. JAR yang akan dibangun ini, sehingga meningkatkan perekonomian masyarakat Kotabaru” tutupnya.
              </p>


